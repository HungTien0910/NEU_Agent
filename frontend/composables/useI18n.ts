const getValue = (obj: Dict, path: string): string | undefined => {
  return path.split('.').reduce((acc, key) => {
    if (!acc || typeof acc === 'string') return undefined;
    return acc[key] as Dict;
  }, obj) as unknown as string | undefined;
};

export const useI18n = () => {
  const { settings, load } = useAppSettings();
  const locale = computed(() => settings.value.language || 'vi');

  const t = (key: string) => {
    const dict = messages[locale.value] || messages.vi;
    const value = getValue(dict, key);
    return value || key;
  };

  return { t, locale, load };
};
